"""Persistence contract used by the research coordinator and its collaborators."""

from contextlib import AbstractContextManager
from pathlib import Path
from typing import Any, Callable, Protocol


class ResearchStore(Protocol):
    root: Path
    on_close: Callable[[], None] | None

    def transaction(self) -> AbstractContextManager: ...

    def put(self, kind: str, ident: str, data: dict) -> None: ...
    def get(self, kind: str, ident: str) -> dict: ...
    def all(self, kind: str) -> list[dict]: ...
    def send(self, recipient: str, sender: str, body: str) -> int: ...
    def pending(self, recipient: str) -> bool: ...
    def take_mail(self, agent: dict) -> None: ...
    def recent_mail(self, recipients: list[str], limit: int = 20) -> list[dict]: ...
    def retire_mail(self, recipient: str) -> None: ...
    def event(self, kind: str, data: dict) -> None: ...
    def receipt(self, agent: str, call_id: str) -> Any: ...
    def save_receipt(self, agent: str, call_id: str, result: Any) -> None: ...
    def archives(self) -> list[dict]: ...
    def sync_events(self) -> None: ...
    def close(self) -> None: ...
